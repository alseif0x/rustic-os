//! SHA-256 of Catalog.digest's expanded descriptors, checked against the schemas
//! by tools/contracts/tests/test_negotiation.py. A digest is not authentication.
use crate::{files::Error, services::Method};

const GET: [u8; 32] = [
    0x25, 0x1c, 0xf4, 0x1a, 0x61, 0x1e, 0x9c, 0x6d, 0xc4, 0xbc, 0x8c, 0x13, 0xf2, 0x31, 0xc6, 0xfc,
    0x75, 0x3f, 0x02, 0xd3, 0xca, 0x80, 0x77, 0x6b, 0xbb, 0xb4, 0x2f, 0x9d, 0xcf, 0x9f, 0x74, 0xd0,
];
const CANCEL: [u8; 32] = [
    0x7d, 0x54, 0x65, 0xb4, 0xf1, 0xd3, 0x03, 0x99, 0xdf, 0xf0, 0x79, 0xf3, 0x3b, 0x9d, 0xb3, 0x56,
    0x26, 0xf3, 0xb5, 0x3a, 0x2f, 0xf7, 0x18, 0x14, 0x53, 0x85, 0x60, 0x9a, 0x98, 0x15, 0x6f, 0x45,
];

pub(super) fn digest(method: Method) -> Result<[u8; 32], Error> {
    match method {
        Method::OperationsGet => Ok(GET),
        Method::OperationsCancel => Ok(CANCEL),
        _ => Err(Error::Unsupported),
    }
}
